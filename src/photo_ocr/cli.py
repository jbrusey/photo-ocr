"""CLI entrypoints for photo_ocr."""

import argparse
from pathlib import Path

import pandas as pd

from .extract import extract_text_from_images
from .match_paths import (
    build_available_paths,
    extract_server_paths_from_csv,
    extract_server_paths_from_rows,
    find_fuzzy_match,
)
from .trash import move_paths_to_trash, validate_folder_name


def extract_text_main() -> None:
    parser = argparse.ArgumentParser(description="Extract OCR text from images")
    parser.add_argument(
        "--download-folder",
        type=Path,
        required=True,
        help="Folder containing images to scan",
    )
    parser.add_argument(
        "--output-csv", type=Path, required=True, help="Output CSV for OCR text"
    )
    parser.add_argument(
        "--img-pattern",
        type=str,
        default="IMG_*",
        help="Glob pattern for image files (default: IMG_*)",
    )

    args = parser.parse_args()

    download_folder = args.download_folder.expanduser().resolve()
    output_csv = args.output_csv.expanduser().resolve()

    rows = extract_text_from_images(download_folder, img_pattern=args.img_pattern)
    pd.DataFrame(rows, columns=["image_file", "extracted_text"]).to_csv(
        output_csv, index=False
    )


